#!/usr/bin/env python3
"""Generate extension/src/shared-config.js from the plugin's config/defaults.json.

One source of truth: pricing, the reference configuration, recommendations and classifier
signals are edited in the plugin's defaults.json and copied into the extension by this script.
Run it after changing defaults.json:  python3 tools/build_extension_config.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "plugins" / "token-steward" / "config" / "defaults.json"
OUT = ROOT / "extension" / "src" / "shared-config.js"

KEYS = ["currency_symbol", "pricing", "aliases", "tier_names", "effort_levels",
        "effort_output_multiplier", "baseline", "recommendations", "classifier"]


def strip_comments(obj):
    if isinstance(obj, dict):
        return {k: strip_comments(v) for k, v in obj.items() if not k.startswith("_")}
    if isinstance(obj, list):
        return [strip_comments(v) for v in obj]
    return obj


def main():
    cfg = strip_comments(json.loads(SRC.read_text(encoding="utf-8")))
    shared = {k: cfg[k] for k in KEYS}
    OUT.write_text(
        "// GENERATED by tools/build_extension_config.py from plugins/token-steward/config/defaults.json.\n"
        "// Do not edit by hand.\n"
        f"globalThis.TOKEN_STEWARD_SHARED = {json.dumps(shared, indent=1)};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
